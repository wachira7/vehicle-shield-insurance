// Copies contract ABIs into packages/protocol: JSON files, plus abis.ts with `as const`
// ABIs so viem and Ponder can type events and function calls.
import fs from "fs";
import path from "path";

const contracts = ["InsuranceCore", "PolicyNFT"];
const protocolDir = path.join(__dirname, "../../packages/protocol");

const lines = ["// Generated by vehicle-backend/scripts/extractAbis.ts. Do not edit.", ""];
for (const name of contracts) {
  const artifact = JSON.parse(
    fs.readFileSync(path.join(__dirname, `../artifacts/contracts/${name}.sol/${name}.json`), "utf8"),
  );
  fs.writeFileSync(path.join(protocolDir, "abis", `${name}.json`), JSON.stringify(artifact.abi, null, 2) + "\n");
  lines.push(`export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`, "");
  console.log(`Extracted ABI for ${name}`);
}
fs.writeFileSync(path.join(protocolDir, "src", "abis.ts"), lines.join("\n"));
